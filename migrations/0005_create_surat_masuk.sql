CREATE TABLE surat_masuk (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    tahun SMALLINT UNSIGNED NOT NULL,
    no_agenda INT UNSIGNED NOT NULL,
    tgl_terima DATE NOT NULL,
    no_surat VARCHAR(100) NOT NULL,
    tgl_surat DATE NOT NULL,
    asal VARCHAR(200) NOT NULL,
    perihal VARCHAR(500) NOT NULL,
    sifat ENUM('biasa','segera','sangat_segera','rahasia') NOT NULL DEFAULT 'biasa',
    klasifikasi_id INT UNSIGNED NOT NULL,
    no_srikandi VARCHAR(100) NULL,
    jumlah_lampiran VARCHAR(50) NULL,
    status ENUM('diterima','didisposisi','selesai','dibatalkan') NOT NULL DEFAULT 'diterima',
    cancelled_at DATETIME NULL,
    cancel_reason VARCHAR(255) NULL,
    created_by INT UNSIGNED NULL,
    updated_by INT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_surat_tahun_agenda (tahun, no_agenda),
    KEY idx_surat_tahun_status (tahun, status),
    KEY idx_surat_tgl_terima (tgl_terima),
    KEY idx_surat_ganda (no_surat, asal, tgl_surat),
    FULLTEXT KEY ft_surat_perihal_asal (perihal, asal),
    CONSTRAINT chk_surat_tgl CHECK (tgl_surat <= tgl_terima),
    CONSTRAINT fk_surat_klasifikasi FOREIGN KEY (klasifikasi_id) REFERENCES klasifikasi_arsip (id) ON DELETE RESTRICT,
    CONSTRAINT fk_surat_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_surat_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
